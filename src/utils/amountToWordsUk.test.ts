import { describe, expect, it } from "vitest";
import {
  amountToWordsUk,
  normalizeAmountInput,
  selectWordForm,
  tripletToWords,
} from "./amountToWordsUk";

const convert = (value: string | number) => {
  const result = amountToWordsUk(value);
  if (!result.ok) throw new Error(result.error);
  return result.text;
};

