describe("helpers and boundary grammar", () => {
  it("uses feminine forms where requested", () => {
    expect(tripletToWords(22, true)).toBe("двадцять дві");
    expect(tripletToWords(22, false)).toBe("двадцять два");
  });

  it.each([
    [1, "a"], [2, "b"], [4, "b"], [5, "c"],
    [11, "c"], [14, "c"], [21, "a"], [22, "b"], [25, "c"],
    [101, "a"], [102, "b"], [111, "c"], [114, "c"],
  ])("selects noun form for %s", (value, expected) => {
    expect(selectWordForm(value, ["a", "b", "c"])).toBe(expected);
  });

  it("normalizes spaces and one-digit fractional input", () => {
    expect(normalizeAmountInput("1\u202f234,5")).toEqual({
      ok: true,
      integer: 1234n,
      kopiyky: 50,
    });
  });

  it("keeps hryvnia forms correct around transitions in different ranges", () => {
    const endings = [1, 2, 3, 4, 5, 11, 12, 13, 14, 21, 22, 23, 24, 25];
    const bases = [0, 100, 1_000, 10_000, 100_000, 1_000_000, 10_000_000, 1_000_000_000];
    const forms = ["гривня", "гривні", "гривень"] as const;

    for (const base of bases) {
      for (const ending of endings) {
        const value = BigInt(base + ending);
        const expectedForm = selectWordForm(value, forms);
        expect(convert(value.toString())).toMatch(new RegExp(`${expectedForm} 00 копійок$`, "u"));
      }
    }
  });

  it("checks every ending from 0 to 999 across large scales", () => {
    const forms = ["гривня", "гривні", "гривень"] as const;
    for (const base of [0n, 1_000_000n, 1_000_000_000n, 1_000_000_000_000n]) {
      for (let ending = 0n; ending < 1_000n; ending += 1n) {
        const value = base + ending;
        expect(convert(value.toString())).toContain(selectWordForm(value, forms));
      }
    }
  });
});
